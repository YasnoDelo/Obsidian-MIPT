#include <iostream>
#include <print>

int main()
{
    constexpr unsigned char first_code = 32;
    constexpr unsigned char last_code = 127;
    char symbol = '\0';
    while (std::cin.get(symbol))
    {
        if (symbol == '\n' || symbol == '\r')
        {
            continue;
        }
        const auto code = static_cast<unsigned char>(symbol);
        if (code < first_code || code > last_code)
        {
            std::print("Expected ASCII codes from 32 through 127.\n");
            return 1;
        }
        switch (symbol)
        {
        case 'A':
        case 'B':
        case 'C':
        case 'D':
        case 'E':
        case 'F':
        case 'G':
        case 'H':
        case 'I':
        case 'J':
        case 'K':
        case 'L':
        case 'M':
        case 'N':
        case 'O':
        case 'P':
        case 'Q':
        case 'R':
        case 'S':
        case 'T':
        case 'U':
        case 'V':
        case 'W':
        case 'X':
        case 'Y':
        case 'Z':
            std::print("uppercase\n");
            break;
        case 'a':
        case 'b':
        case 'c':
        case 'd':
        case 'e':
        case 'f':
        case 'g':
        case 'h':
        case 'i':
        case 'j':
        case 'k':
        case 'l':
        case 'm':
        case 'n':
        case 'o':
        case 'p':
        case 'q':
        case 'r':
        case 's':
        case 't':
        case 'u':
        case 'v':
        case 'w':
        case 'x':
        case 'y':
        case 'z':
            std::print("lowercase\n");
            break;
        case '0':
        case '1':
        case '2':
        case '3':
        case '4':
        case '5':
        case '6':
        case '7':
        case '8':
        case '9':
            std::print("digit\n");
            break;
        case '!':
        case '"':
        case '#':
        case '$':
        case '%':
        case '&':
        case '\'':
        case '(':
        case ')':
        case '*':
        case '+':
        case ',':
        case '-':
        case '.':
        case '/':
        case ':':
        case ';':
        case '<':
        case '=':
        case '>':
        case '?':
        case '@':
        case '[':
        case '\\':
        case ']':
        case '^':
        case '_':
        case '`':
        case '{':
        case '|':
        case '}':
        case '~':
            std::print("punctuation\n");
            break;
        default:
            std::print("other\n");
            break;
        }
    }
    return std::cin.bad() ? 1 : 0;
}
